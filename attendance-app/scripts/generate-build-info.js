// Writes the current timestamp into src/app/build-info.ts so the app can
// display when it was last built. Run before production builds.
const fs = require('fs');
const path = require('path');

const timestamp = new Date().toISOString();
const outPath = path.join(__dirname, '..', 'src', 'app', 'build-info.ts');
const content = `// Auto-generated by scripts/generate-build-info.js. Do not edit manually.
export const BUILD_TIMESTAMP = '${timestamp}';
`;

fs.writeFileSync(outPath, content);
console.log(`Generated build-info.ts with timestamp ${timestamp}`);
